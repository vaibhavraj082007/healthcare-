function result = segment_structures(imagePath, outputDir, options)
% SEGMENT_STRUCTURES Orchestrate modular retinal structure segmentation.
%
% Integrates 4 transparent modular components:
%   1. Field-of-View Segmentation  (segment_fov.m)
%   2. Optic Disc Localization     (segment_optic_disc.m)
%   3. Fovea / Macula Localization (localize_fovea.m)
%   4. Retinal Vessel Segmentation (segment_vessels.m)
%
% Features:
%   - Resistant to false positives (exudates as OD, hemorrhages as fovea)
%   - Explicit failure indicators rather than fabricated coordinates
%   - Inferred or user-provided laterality handling (OD vs OS)
%   - Out-of-FOV structure handling (disc-centered or macula-centered shots)
%   - Binary masks and coordinates mapped back to original image dimensions
%   - Experimental status labeling and reliability metrics
%
% USAGE:
%   result = segment_structures('path/to/fundus.jpg', 'path/to/output/')
%   result = segment_structures(imagePath, outputDir, 'laterality', 'OD')
%
% INPUTS:
%   imagePath - (string) Full path to the input fundus image
%   outputDir - (string) Directory to save segmentation mask artifacts
%   options   - Name-value pairs:
%       'laterality'     - (string) 'auto' | 'OD' | 'OS' | 'unknown' (default: 'auto')
%       'fovModel'       - (string) Optional path to learned FOV model
%       'odModel'        - (string) Optional path to learned OD model
%       'foveaModel'     - (string) Optional path to learned fovea model
%       'vesselModel'    - (string) Optional path to learned vessel model
%
% OUTPUT:
%   result - (struct) Full structure analysis matching RetinaShield schema:
%     .field_of_view - struct with mask_path, bounding_box, area_ratio, is_reliable
%     .optic_disc    - struct with detected, center_x, center_y, radius, mask_path, confidence, is_reliable, failure_reason
%     .macula        - struct (backwards compatible) with detected, center_x, center_y, confidence, is_reliable, inferred_laterality
%     .fovea         - struct with full anatomical details
%     .vasculature   - struct with segmentation_mask_path, vessel_density, tortuosity_index, is_reliable
%     .is_experimental - Boolean true (labelled experimental until validated)
%     .disclaimer    - Research screening disclaimer
%
% Copyright (c) 2026 RetinaShield Research Project

    arguments
        imagePath (1,1) string {mustBeFile}
        outputDir (1,1) string
        options.laterality (1,1) string = "auto"
        options.fovModel (1,1) string = ""
        options.odModel (1,1) string = ""
        options.foveaModel (1,1) string = ""
        options.vesselModel (1,1) string = ""
    end

    if ~isfolder(outputDir)
        mkdir(outputDir);
    end

    img = imread(imagePath);
    [rows, cols, ~] = size(img);
    [~, baseName, ~] = fileparts(imagePath);

    fprintf('[RetinaShield Structure Pipeline] Image: %s (%dx%d)\n', baseName, cols, rows);

    % -----------------------------------------------------------------------
    % 1. Retinal Field-of-View (FOV) Segmentation
    % -----------------------------------------------------------------------
    fprintf('  - [1/4] Segmenting Field of View...\n');
    try
        fov = segment_fov(img, ...
            'outputDir', outputDir, ...
            'modelPath', options.fovModel);
    catch ME
        warning('segment_structures:fovFailed', 'FOV segmentation failed: %s', ME.message);
        fov = struct('mask', true(rows, cols), 'mask_path', '', ...
                     'bounding_box', [1, 1, cols, rows], 'center', [cols/2, rows/2], ...
                     'radius', min(rows, cols)/2, 'area_pixels', rows*cols, ...
                     'area_ratio', 1.0, 'is_reliable', false, ...
                     'failure_reason', sprintf('FOV_ERROR: %s', ME.message), ...
                     'algorithm_version', '0.2.0-fallback', 'method', 'fallback_full_frame');
    end

    % -----------------------------------------------------------------------
    % 2. Retinal Vasculature Segmentation
    % -----------------------------------------------------------------------
    fprintf('  - [2/4] Segmenting Retinal Vasculature...\n');
    try
        vasc = segment_vessels(img, ...
            'fovMask', fov.mask, ...
            'outputDir', outputDir, ...
            'modelPath', options.vesselModel);
    catch ME
        warning('segment_structures:vesselFailed', 'Vessel segmentation failed: %s', ME.message);
        vasc = struct('mask', false(rows, cols), 'skeleton_mask', false(rows, cols), ...
                      'mask_path', '', 'vessel_density', 0.0, 'tortuosity_index', 1.0, ...
                      'caliber_proxy', 0.0, 'confidence', 0.0, 'is_reliable', false, ...
                      'failure_reason', sprintf('VESSEL_ERROR: %s', ME.message), ...
                      'algorithm_version', '0.2.0-fallback', 'method', 'fallback');
    end

    % -----------------------------------------------------------------------
    % 3. Optic Disc Localization and Segmentation
    % -----------------------------------------------------------------------
    fprintf('  - [3/4] Localizing & Segmenting Optic Disc...\n');
    try
        od = segment_optic_disc(img, ...
            'fovMask', fov.mask, ...
            'vesselMask', vasc.mask, ...
            'outputDir', outputDir, ...
            'modelPath', options.odModel);
    catch ME
        warning('segment_structures:odFailed', 'Optic disc segmentation failed: %s', ME.message);
        od = struct('detected', false, 'center_x', NaN, 'center_y', NaN, ...
                    'radius', NaN, 'mask', false(rows, cols), 'mask_path', '', ...
                    'confidence', 0.0, 'is_reliable', false, ...
                    'failure_reason', sprintf('OD_ERROR: %s', ME.message), ...
                    'algorithm_version', '0.2.0-fallback', 'method', 'fallback');
    end

    % -----------------------------------------------------------------------
    % 4. Fovea / Macula Localization
    % -----------------------------------------------------------------------
    fprintf('  - [4/4] Localizing Fovea & Evaluating Laterality...\n');
    try
        fovea = localize_fovea(img, od, ...
            'fovMask', fov.mask, ...
            'vesselMask', vasc.mask, ...
            'laterality', options.laterality, ...
            'outputDir', outputDir, ...
            'modelPath', options.foveaModel);
    catch ME
        warning('segment_structures:foveaFailed', 'Fovea localization failed: %s', ME.message);
        fovea = struct('detected', false, 'center_x', NaN, 'center_y', NaN, ...
                       'radius', NaN, 'confidence', 0.0, 'is_reliable', false, ...
                       'failure_reason', sprintf('FOVEA_ERROR: %s', ME.message), ...
                       'inferred_laterality', 'unknown', ...
                       'anatomical_vector', struct('dx', NaN, 'dy', NaN, 'distance_dd', NaN), ...
                       'algorithm_version', '0.2.0-fallback', 'method', 'fallback');
    end

    % -----------------------------------------------------------------------
    % Assemble Unified Structure Analysis Result
    % -----------------------------------------------------------------------
    result = struct();

    % Field of View
    result.field_of_view = struct(...
        'mask_path', fov.mask_path, ...
        'bounding_box', fov.bounding_box, ...
        'center_x', fov.center(1), ...
        'center_y', fov.center(2), ...
        'radius', fov.radius, ...
        'area_pixels', fov.area_pixels, ...
        'area_ratio', fov.area_ratio, ...
        'is_reliable', fov.is_reliable, ...
        'failure_reason', fov.failure_reason, ...
        'algorithm_version', fov.algorithm_version ...
    );

    % Optic Disc
    result.optic_disc = struct(...
        'detected', od.detected, ...
        'center_x', od.center_x, ...
        'center_y', od.center_y, ...
        'radius', od.radius, ...
        'mask_path', od.mask_path, ...
        'confidence', od.confidence, ...
        'is_reliable', od.is_reliable, ...
        'failure_reason', od.failure_reason, ...
        'algorithm_version', od.algorithm_version ...
    );

    % Fovea & Backwards-compatible Macula
    maculaStruct = struct(...
        'detected', fovea.detected, ...
        'center_x', fovea.center_x, ...
        'center_y', fovea.center_y, ...
        'radius', fovea.radius, ...
        'confidence', fovea.confidence, ...
        'is_reliable', fovea.is_reliable, ...
        'failure_reason', fovea.failure_reason, ...
        'inferred_laterality', fovea.inferred_laterality, ...
        'anatomical_vector', fovea.anatomical_vector, ...
        'algorithm_version', fovea.algorithm_version ...
    );
    result.macula = maculaStruct;
    result.fovea = maculaStruct;

    % Vasculature
    result.vasculature = struct(...
        'segmentation_mask_path', vasc.mask_path, ...
        'vessel_density', vasc.vessel_density, ...
        'tortuosity_index', vasc.tortuosity_index, ...
        'caliber_proxy', vasc.caliber_proxy, ...
        'confidence', vasc.confidence, ...
        'is_reliable', vasc.is_reliable, ...
        'failure_reason', vasc.failure_reason, ...
        'algorithm_version', vasc.algorithm_version ...
    );

    % Metadata & Experimental Clinical Disclaimer
    result.is_experimental = true;
    result.disclaimer = 'EXPERIMENTAL BASELINE — Retinal structure segmentation and anatomical localization are research baselines. Not certified for autonomous clinical diagnostic decisions.';

    fprintf('[RetinaShield Structure Pipeline Done] OD: %s (conf=%.2f, reliable=%s) | Fovea: %s (lat=%s) | VascDensity: %.3f\n', ...
        mat2str(od.detected), od.confidence, mat2str(od.is_reliable), ...
        mat2str(fovea.detected), fovea.inferred_laterality, ...
        vasc.vessel_density);
end
